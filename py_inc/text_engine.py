from pathlib import Path
import pygame as pg
from py_inc.drawing import Cell
from py_inc.consts import *
from py_inc.font12 import font12
HERE = Path(__file__).parent


def draw_string(
    surface: pg.Surface,
    string: str
):
    """
    Wrapper for abstracting out the details of drawing strings
    to the screen, calls into `draw_buffer_chars`
    """
    buffer_data = [[[] for _ in range(4)] for _ in range(nlines)]
    j = 0
    line = 0
    for _, char in enumerate(string):
        if j > sum(buffer_nchars) - 1:
            j = 0
            line += 1

        if j < buffer_start_pos[1]:
            buffer = 0
        elif buffer_start_pos[1] <= j < buffer_start_pos[2]:
            buffer = 1
        elif buffer_start_pos[2] <= j < buffer_start_pos[3]:
            buffer = 2
        elif buffer_start_pos[3] <= j:
            buffer = 3

        buffer_data[line][buffer].append(char)
        j += 1

    # Draw strings in buffer data
    for line in range(nlines):
        draw_buffer_chars(surface, 0, line, buffer_data, colour="RED")
        draw_buffer_chars(surface, 1, line, buffer_data)
        draw_buffer_chars(surface, 2, line, buffer_data, colour="BLUE")
        draw_buffer_chars(surface, 3, line, buffer_data)

    return buffer_data


def draw_buffer_chars(
    surface: pg.Surface,
    buffer: int,
    line: int,
    buffer_data: str,
    colour: str = "BLACK",
    x: int | None = None,
    y: int | None = None
):
    """ Draw individual characters in the given line and buffer to the screen """
    if None in (x, y):
        x, y = char_start
        for i in range(buffer):
            # Offset by previous buffers
            x += buffer_nchars[i] * char_width
        y += line * line_spacing

    chars = buffer_data[line][buffer]
    if len(chars) < buffer_nchars[buffer]:
        chars += [" "] * (buffer_nchars[buffer] - len(chars))

    for char in chars:
        letter = font12[char]
        for i, row in enumerate(letter):
            for j, state in enumerate(row):
                c = colour if state else "WHITE"
                xpos, ypos = x + j, y + i
                Cell(
                    surface, position=(xpos, ypos), pixel_size=pixel_size, colour=c
                )
        x += char_width


def output_cpp_code_to_file(
    buffer_data: list,
    func_name: str,
    file: str = "cpp_out",
    write_mode: str = "w"
):
    """
    Print the Arduino c++ code required to display
    the drawn string to the physical ePaper display

    Ideally a similar wrapper to `draw_string` would
    be created in the Arduino c++ environment but this
    is a quick solution for getting the EPD displaying arbitrary text
    """
    # First check if func_name already in cpp files
    with open(HERE / ".." / f"{file}.h", "r") as f:
        lines = f.readlines()
    for line in lines:
        if f"{func_name}(" in line:
            print(f"Function name '{func_name}' already exists in {file}.h and {file}.cpp")
            return

    include = [
        "#include \"epd2in13_V4.h\"\n",
        "#include \"epdpaint.h\"\n\n",
    ]
    if write_mode == "w":
        code = "#define COLORED     0\n#define UNCOLORED   1\n\n"
    else:
        code = ""
    func_sig = f"void {func_name}(Paint& paint, Epd& epd, unsigned char* image) {{\n"
    code += func_sig

    for buffer in range(4):
        code += f"  // Draw buffer {buffer}\n"
        code += "  paint.Clear(UNCOLORED);\n"
        x = char_start[0] if buffer == 0 else 0
        for line_num, line in enumerate(buffer_data):
            y = char_start[0] + line_num * line_spacing # Offset y by line spacing
            this_line_data = "".join(line[buffer])
            code += f"  paint.DrawStringAt({x}, {y}, \"{this_line_data}\", &Font12, COLORED);\n"
        code += "  epd.Display1(image);\n\n"
    code += "}\n"

    # Write header file
    with open(HERE / ".." / f"{file}.h", write_mode) as f:
        if write_mode == "w":
            f.write("// Header file generated by `output_cpp_code_to_file` in `text_engine.py`\n")
            for inc in include:
                f.write(inc)
        f.write(f"{func_sig.split(" {")[0]};\n")

    # Write cpp file
    with open(HERE / ".." / f"{file}.cpp", write_mode) as f:
        if write_mode == "w":
            f.write("// File generated by `output_cpp_code_to_file` in `text_engine.py`\n")
            f.write(f"#include \"{file}.h\"\n")
            for inc in include:
                f.write(inc)
        f.write(code)
